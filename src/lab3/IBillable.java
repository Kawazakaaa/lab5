package lab3;
/**
 * Контракт для объектов, для которых можно рассчитать стоимость оказанных услуг.
 * <p>
 * В системе медицинского обслуживания реализуется классом {@link Patient} —
 * стоимость лечения рассчитывается по количеству назначенных процедур.
 *
 * @author Цаболов Арсен
 * @version 1.0
 * @since 1.0
 * @see Patient
 */
public interface IBillable {

    /**
     * Вычисляет итоговую стоимость лечения объекта.
     *
     * @return стоимость в рублях (неотрицательное число)
     */
    double calculateBill();
}